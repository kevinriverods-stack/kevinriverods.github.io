let currentLanguage = "es";

const languageSwitch = document.getElementById("languageSwitch");

function updateTechnologies() {
  const techList = document.querySelector(".tech-list");

  if (!techList) {
    console.warn("The .tech-list element was not found.");
    return;
  }

  techList.innerHTML = technologies
    .map(technology => `<b>${technology}</b>`)
    .join("");
}

function setLanguage(language) {
  if (!translations[language]) {
    console.warn(`Language "${language}" is not supported.`);
    return;
  }

  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (translations[language][key] !== undefined) {
      element.innerHTML = translations[language][key];
    }
  });

  updateTechnologies();

  if (languageSwitch) {
    languageSwitch.textContent = language === "es" ? "EN" : "ES";

    languageSwitch.setAttribute(
      "aria-label",
      language === "es" ? "Switch to English" : "Cambiar a español"
    );
  }
}

// Language selector
if (languageSwitch) {
  languageSwitch.addEventListener("click", () => {
    setLanguage(currentLanguage === "es" ? "en" : "es");
  });
}

// Current year
const yearElement = document.getElementById("year");

if (yearElement) {
  yearElement.textContent = new Date().getFullYear();
}

// Mobile navigation
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

if (menuToggle && navLinks) {
  menuToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("open");

    menuToggle.setAttribute("aria-expanded", String(isOpen));
  });

  navLinks.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
      navLinks.classList.remove("open");
      menuToggle.setAttribute("aria-expanded", "false");
    });
  });
}

// Initialise website in Spanish
setLanguage("es");
